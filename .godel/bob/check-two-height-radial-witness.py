# Verify exactly the constant and linear coefficients in m for the circle
# law with masses [1-m*(node + node^-1)]/11, before rotating the grid.
zeta = CyclotomicField(22).gen()
nodes = [zeta**(2*l+1) for l in range(11)]
for j in range(10):
    assert sum(node**j for node in nodes) == 11*(j == 0)
    assert sum(node**j*(node+node**(-1)) for node in nodes) == 11*(j == 1)
print('circle moments through order 9: exact')

times = [t+2 for t in z]


def phases(x):
    return [K(0, -t*x).exp() for t in times]


def certify(name, levels):
    jump = [(v-u)*F(-t/2).exp() for t, v, u in zip(z, levels, [QQ(0)]+levels)]
    B = [sum(abs(v)*F(abs(t)**k) for t, v in zip(times, jump)) for k in range(5)]
    assert B[0]/X < cap  # Tail for either sign of x.

    # Check the jump formula against direct slab integration at fixed x.
    for x in (QQ(0), QQ(17)/4, QQ(13)):
        w = K(QQ(1)/2, x)
        edges = [(-w*t).exp() for t in z] + [K(0)]
        slab = sum(v*(l-r) for v, l, r in zip(levels, edges, edges[1:]))/w
        via_jumps = K(0, 2*x).exp()*sum(v*p for v, p in zip(jump, phases(x)))/w
        assert abs(slab-via_jumps) < F('1e-30')

    # Q = |N|^2-cap^2*(1/4+x^2), where N is the centered jump polynomial.
    # Use its first three point derivatives and a global fourth derivative bound.
    coeffs = [[K(v)*K(0, -t)**k for t, v in zip(times, jump)] for k in range(4)]
    M4 = sum(comb(4, k)*B[k]*B[4-k] for k in range(5))
    cap2 = cap**2

    def passes(mid, radius):
        p = phases(mid)
        nd = [sum(v*w for v, w in zip(row, p)) for row in coeffs]
        conj = [v.conjugate() for v in nd]
        radial = [F(QQ(1)/4+mid**2), F(2*mid), F(2), F(0)]
        q = [sum(comb(k, j)*(nd[j]*conj[k-j]).real() for j in range(k+1))
             -cap2*radial[k] for k in range(4)]
        r = F(radius)
        upper = q[0]+sum(abs(q[k])*r**k/factorial(k) for k in range(1, 4))
        return upper+M4*r**4/24 < 0

    stack, boxes = [(QQ(0), X, 0)], 0
    while stack:
        lo, hi, depth = stack.pop()
        mid = (lo+hi)/2
        if passes(mid, (hi-lo)/2):
            boxes += 1
        else:
            assert depth < 22, (lo, hi)
            stack.extend([(lo, mid, depth+1), (mid, hi, depth+1)])
    print(name, 'cap:', cap, '; finite boxes:', boxes, '; tail bound at', X, ':', B[0]/X,
          flush=True)


