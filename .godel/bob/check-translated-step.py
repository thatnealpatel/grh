z = [QQ(t)/1024 for t, _ in DATA]
a = [QQ(v)/10**12 for _, v in DATA]
assert z[0] == -12 and 0 in z and z[-1] == 16
assert all(l < r for l, r in zip(z, z[1:]))
assert all(-1 <= v <= 1 for v in a)

# Angular mean under the probability density z*exp(-z) on z >= 0.
weight_tail = [(1+t)*F(-t).exp() for t in z] + [F(0)]
mean = sum((weight_tail[j]-weight_tail[j+1])*F((1+a[j])/2).sqrt()
           for j, t in enumerate(z) if t >= 0)
assert mean - F(QQ(8)/9) > F(QQ(1)/20000000)
print('angular mean minus 8/9:', mean - F(QQ(8)/9), flush=True)

# Jhat(x) = sum b_j exp(-ix z_j)/(1/2+ix).
b = [(v-u)*F(-t/2).exp() for t, v, u in zip(z, a, [QQ(0)]+a)]
cap = F(QQ(61505322)/10**8)
X = QQ(64)
# Center the jump polynomial at z=-2 for tighter derivative bounds.
# N(x) = sum b_j exp(-ix (z_j+2)); the unit phase leaves its modulus unchanged.
times = [t+2 for t in z]
B = [sum(abs(v)*F(abs(t)**k) for t, v in zip(times, b)) for k in range(5)]
assert B[0]/X < cap  # |Jhat(x)| <= sum |b_j|/|x| for |x| >= X.
print('jump tail bound at', X, ':', B[0]/X, flush=True)


def phases(x):
    return [K(0, -t*x).exp() for t in times]


# Cross-check the jump formula against separate slab integrals at exact x.
for x in (QQ(0), QQ(17)/4, QQ(13)):
    w = K(QQ(1)/2, x)
    edges = [(-w*t).exp() for t in z] + [K(0)]
    slab = sum(v*(l-r) for v, l, r in zip(a, edges, edges[1:]))/w
    jump = K(0, 2*x).exp()*sum(v*p for v, p in zip(b, phases(x)))/w
    assert abs(slab-jump) < F(QQ(1)/10**30)

# Q(x) = |N(x)|^2 - cap^2*(1/4+x^2). Its fourth derivative is
# bounded in modulus by the product-rule bound M4 (B[k] bounds |N^(k)|).
M4 = sum(comb(4, k)*B[k]*B[4-k] for k in range(5))
coeffs = [[K(v)*K(0, -t)**k for t, v in zip(times, b)] for k in range(4)]
cap2 = cap**2


def passes(mid, radius):
    p = phases(mid)
    nd = [sum(v*w for v, w in zip(row, p)) for row in coeffs]
    nc = [v.conjugate() for v in nd]
    radial = [F(QQ(1)/4+mid**2), F(2*mid), F(2), F(0)]
    q = [sum(comb(k, j)*(nd[j]*nc[k-j]).real() for j in range(k+1))
         - cap2*radial[k] for k in range(4)]
    r = F(radius)
    upper = q[0] + sum(abs(q[k])*r**k/factorial(k) for k in range(1, 4))
    return upper + M4*r**4/24 < 0


# Taylor's theorem covers every point of the box, not only the midpoint.
# Real a implies even |Jhat|, so cover [0, X] and use the tail above.
stack = [(QQ(0), X, 0)]
boxes = 0
while stack:
    lo, hi, depth = stack.pop()
    mid = (lo+hi)/2
    if passes(mid, (hi-lo)/2):
        boxes += 1
    else:
        assert depth < 24, (lo, hi)
        stack.extend([(lo, mid, depth+1), (mid, hi, depth+1)])
print('all-frequency cap:', cap, '; finite boxes:', boxes, flush=True)

c = F(QQ(39)/20)


def cutoff(n):
    return c.cosh()/(6*(F.pi()/(n+2)).cos())


slack = cutoff(11) - cap
